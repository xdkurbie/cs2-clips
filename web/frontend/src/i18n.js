export function detectLang() {
  const saved = localStorage.getItem("cs2clips.lang");
  if (saved === "nb" || saved === "en") return saved;
  return (navigator.language || "").toLowerCase().startsWith("en") ? "en" : "nb";
}

export function useI18n() {
  const [lang, setLang] = useState(detectLang);
  useEffect(() => localStorage.setItem("cs2clips.lang", lang), [lang]);
  const t = STR[lang];
  return { lang, t, toggle: () => setLang(lang === "nb" ? "en" : "nb") };
}

export function titleOf(h, t) {
  const kind = h.kind === "multikill" ? `${h.kills}K` : h.kind === "clutch" ? `1v${h.enemies || "?"} ${t.clutch}` : t[h.kind] || h.kind;
  const gun = (h.weapon || "").replace(/^weapon_/, "");
  return `${kind}${gun ? ` · ${gun}` : ""}`;
}
