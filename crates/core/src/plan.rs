//! Clip plans and CS2 demo-playback control.
//!
//! Recording works only through CS2's own demo player: CS2 is launched with
//! `-insecure` (VAC off, cannot join secure servers) and `-netconport`, the
//! official console port, over which we send `playdemo`, `demo_gototick`,
//! `spec_player`, ... No injection, no memory access.

use crate::detect::Highlight;
use serde::{Deserialize, Serialize};
use std::io::{BufRead, BufReader, Write};
use std::net::TcpStream;
use std::path::{Path, PathBuf};
use std::time::Duration;

pub const CS2_APPID: &str = "730";
pub const NETCON_PORT: u16 = 29_015;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ClipItem {
    pub id: String,
    pub title: String,
    pub round: u32,
    pub steamid: u64,
    pub player: String,
    pub start_tick: u32,
    pub end_tick: u32,
    pub score: i32,
    pub enabled: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct ClipPlan {
    pub demo: PathBuf,
    pub tickrate: f32,
    pub items: Vec<ClipItem>,
}

impl ClipPlan {
    pub fn new(demo: &Path, tickrate: f32, hs: &[Highlight]) -> Self {
        let items = hs
            .iter()
            .map(|h| ClipItem {
                id: h.id(),
                title: h.title(),
                round: h.round,
                steamid: h.steamid,
                player: h.name.clone(),
                start_tick: h.start_tick,
                end_tick: h.end_tick,
                score: h.score,
                enabled: true,
            })
            .collect();
        Self {
            demo: demo.to_path_buf(),
            tickrate: if tickrate > 0.0 { tickrate } else { 64.0 },
            items,
        }
    }

    pub fn seconds(&self, it: &ClipItem) -> f32 {
        (it.end_tick.saturating_sub(it.start_tick)) as f32 / self.tickrate
    }

    /// (offset_s, item) for every enabled clip in a montage with `transition_s` overlaps.
    pub fn timeline(&self, transition_s: f32) -> Vec<(f32, &ClipItem)> {
        let mut t = 0.0;
        let mut v = Vec::new();
        for it in self.items.iter().filter(|i| i.enabled) {
            v.push((t, it));
            t += (self.seconds(it) - transition_s).max(0.0);
        }
        v
    }

    pub fn total_seconds(&self, transition_s: f32) -> f32 {
        let n = self.items.iter().filter(|i| i.enabled).count();
        let sum: f32 = self
            .items
            .iter()
            .filter(|i| i.enabled)
            .map(|i| self.seconds(i))
            .sum();
        (sum - transition_s * n.saturating_sub(1) as f32).max(0.0)
    }
}

/// Console commands that position the demo for one clip.
pub fn clip_commands(demo_rel: &str, it: &ClipItem, first: bool, hide_hud: bool) -> Vec<String> {
    let mut v = Vec::new();
    if first {
        v.push(format!("playdemo \"{}\"", demo_rel.replace('"', "")));
    }
    v.push("demo_pause".into());
    v.push(format!("demo_gototick {}", it.start_tick));
    v.push(format!(
        "spec_player_by_accountid {}",
        it.steamid.wrapping_sub(76_561_197_960_265_728)
    ));
    v.push("spec_mode 1".into());
    v.push(if hide_hud {
        "cl_draw_only_deathnotices 1".into()
    } else {
        "cl_draw_only_deathnotices 0".into()
    });
    v.push("voice_enable 0".into());
    v
}

/// A `.cfg` equivalent of [`clip_commands`] (for manual use: `exec cs2clips`).
pub fn make_cfg(demo_rel: &str, it: &ClipItem) -> String {
    let mut s = String::from("// generated by CS2 Clips: demo playback only\n");
    for c in clip_commands(demo_rel, it, true, false) {
        s.push_str(&c);
        s.push('\n');
    }
    s.push_str("demo_resume\n");
    s
}

pub fn cs2_launch_args(steam_exe: &str, w: u32, h: u32) -> Vec<String> {
    [
        steam_exe,
        "-applaunch",
        CS2_APPID,
        "-insecure",
        "-novid",
        "-console",
        "-fullscreen",
        "-w",
    ]
    .iter()
    .map(|s| s.to_string())
    .chain([
        w.to_string(),
        "-h".into(),
        h.to_string(),
        "-netconport".into(),
        NETCON_PORT.to_string(),
    ])
    .collect()
}

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum SafetyError {
    #[error("refusing: CS2 must be launched with -insecure for demo recording")]
    NotInsecure,
    #[error("refusing: launch arguments would start online play ({0})")]
    Online(String),
    #[error("refusing: command {0:?} is not allowed during recording")]
    Command(String),
}

pub fn check_launch_safety(args: &[String]) -> Result<(), SafetyError> {
    if !args.iter().any(|a| a == "-insecure") {
        return Err(SafetyError::NotInsecure);
    }
    for b in ["+connect", "+map", "+matchmaking", "+gameui_activate"] {
        if args.iter().any(|a| a == b) {
            return Err(SafetyError::Online(b.into()));
        }
    }
    Ok(())
}

/// Only demo / spectator / cosmetic commands are ever sent to the console.
pub fn check_command(cmd: &str) -> Result<(), SafetyError> {
    const ALLOWED: &[&str] = &[
        "playdemo",
        "demo_pause",
        "demo_resume",
        "demo_gototick",
        "demo_timescale",
        "spec_player",
        "spec_player_by_accountid",
        "spec_mode",
        "cl_draw_only_deathnotices",
        "cl_drawhud",
        "voice_enable",
        "disconnect",
        "echo",
        "volume",
        "snd_setmixer",
        "hideconsole",
        "mirv_streams",
        "host_framerate",
    ];
    let head = cmd.split_whitespace().next().unwrap_or("");
    if ALLOWED.contains(&head) {
        Ok(())
    } else {
        Err(SafetyError::Command(head.into()))
    }
}

/// Connection to CS2's `-netconport` console.
pub struct Netcon {
    stream: TcpStream,
}

impl Netcon {
    pub fn connect(port: u16, timeout: Duration) -> std::io::Result<Self> {
        let addr = ("127.0.0.1", port);
        let stream = TcpStream::connect_timeout(
            &std::net::ToSocketAddrs::to_socket_addrs(&addr)?
                .next()
                .unwrap(),
            timeout,
        )?;
        stream.set_read_timeout(Some(Duration::from_millis(200)))?;
        Ok(Self { stream })
    }

    pub fn send(&mut self, cmd: &str) -> Result<(), String> {
        check_command(cmd).map_err(|e| e.to_string())?;
        self.stream
            .write_all(format!("{cmd}\n").as_bytes())
            .map_err(|e| e.to_string())
    }

    /// Drain console output (best effort) and return lines.
    pub fn read_lines(&mut self) -> Vec<String> {
        let mut out = Vec::new();
        let mut r = BufReader::new(&self.stream);
        let mut line = String::new();
        while let Ok(n) = r.read_line(&mut line) {
            if n == 0 {
                break;
            }
            out.push(line.trim_end().to_string());
            line.clear();
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn item(s: u32, e: u32) -> ClipItem {
        ClipItem {
            id: "x".into(),
            title: "t".into(),
            round: 1,
            steamid: 76561198000000001,
            player: "p".into(),
            start_tick: s,
            end_tick: e,
            score: 1,
            enabled: true,
        }
    }

    #[test]
    fn timeline_offsets() {
        let p = ClipPlan {
            demo: "a.dem".into(),
            tickrate: 64.0,
            items: vec![item(0, 640), item(1000, 1320), item(0, 64)],
        };
        let t = p.timeline(0.5);
        assert_eq!(t.len(), 3);
        assert_eq!(t[1].0, 9.5);
        assert_eq!(t[2].0, 14.0);
        assert!((p.total_seconds(0.5) - 15.0).abs() < 1e-4);
    }

    #[test]
    fn safety_checks() {
        let args = cs2_launch_args("steam.exe", 1920, 1080);
        assert!(check_launch_safety(&args).is_ok());
        let mut bad = args.clone();
        bad.retain(|a| a != "-insecure");
        assert_eq!(check_launch_safety(&bad), Err(SafetyError::NotInsecure));
        bad = args.clone();
        bad.push("+connect".into());
        assert!(check_launch_safety(&bad).is_err());
        assert!(check_command("demo_gototick 100").is_ok());
        assert!(check_command("connect 1.2.3.4").is_err());
        assert!(check_command("sv_cheats 1").is_err());
    }

    #[test]
    fn cfg_contains_seek_and_accountid() {
        let c = make_cfg("replays/match", &item(1234, 2000));
        assert!(c.contains("playdemo \"replays/match\""));
        assert!(c.contains("demo_gototick 1234"));
        assert!(c.contains("spec_player_by_accountid 39734273"));
    }
}
